testthat::test_that("two archive years own overlapping retained current dates",{
  root<-tempfile();dir.create(root);withr::defer(unlink(root,recursive=TRUE))
  current<-file.path(root,"current");dir.create(current)
  jsonlite::write_json(list(days=lapply(c("2026-09-30","2026-10-01","2026-10-05"),function(d)list(date=d))),file.path(current,"daily-data.json"),auto_unbox=TRUE)
  dirs<-file.path(root,c("wy2025","wy2026"))
  for(i in seq_along(dirs)) {
    dir.create(dirs[i]);writeLines("release marker",file.path(dirs[i],paste0("wy",2024L+i,"-release.json")))
    dates<-if(i==1L)"2025-09-30"else c("2025-10-01","2026-09-30")
    months<-lapply(dates,function(d)list(month=substr(d,1,7),water_year=2024L+i,dates=list(d),viewer=paste0("months/",substr(d,1,7),"/index.html")))
    jsonlite::write_json(list(months=months),file.path(dirs[i],"archive-catalog.json"),auto_unbox=TRUE)
  }
  catalog<-connected_explorer_catalog(current,dirs)
  testthat::expect_identical(catalog$latest,"2026-10-05")
  testthat::expect_length(catalog$months,4L)
  archived<-Filter(function(m)m$kind=="archive",catalog$months)
  testthat::expect_identical(archived[[2]]$viewer,"archive/wy2026/months/2025-10/index.html")
  testthat::expect_identical(Filter(function(m)m$kind=="current",catalog$months)[[1]]$month,"2026-10")
  testthat::expect_identical(anyDuplicated(unlist(lapply(catalog$months,`[[`,"dates"))),0L)
  testthat::expect_error(connected_explorer_archives(c(dirs[1],dirs[1])),"Duplicate archive")
})
testthat::test_that("local UI adapters replace the bridge and restore the requested current month",{
  html<-'<head><script src="archive-month-bridge.swc-1234567890abcdef.js" defer></script></head>'
  adapted<-connected_explorer_frame_html(html,"../../../../connected-bridge.js")
  testthat::expect_false(grepl("archive-month-bridge",adapted,fixed=TRUE))
  testthat::expect_true(grepl('../../../../connected-bridge.js',adapted,fixed=TRUE))
  withr::local_dir(connected_test_root)
  js<-paste(readLines("scripts/daily-explorer-assets/explorer.js"),collapse="\n")
  result<-connected_explorer_current_js(js)
  testthat::expect_true(grepl("day.date.startsWith(connectedMonth)",result,fixed=TRUE))
  testthat::expect_true(grepl("byDate.has(connectedDate)",result,fixed=TRUE))
  testthat::expect_true(grepl("parent.postMessage({type:'swc:connected-month'",result,fixed=TRUE))
  testthat::expect_true(grepl("img.dataset.connectedSrc = image",result,fixed=TRUE))
  testthat::expect_true(grepl("image.dataset.connectedSrc = source",result,fixed=TRUE))
  testthat::expect_error(connected_explorer_current_js("bad hook"),"needs review")
})
testthat::test_that("preview server only serves allowed files and never writes to sources",{
  root<-tempfile("connected-server-");dir.create(root)
  withr::defer(unlink(root,recursive=TRUE))
  for(d in c("preview","overrides","current","archive"))dir.create(file.path(root,d))
  writeLines("app",file.path(root,"preview/index.html"))
  writeLines("current",file.path(root,"overrides/current-index.html"))
  writeLines("private",file.path(root,"current/secret.txt"))
  writeBin(as.raw(c(1,2,3)),file.path(root,"current/map.png"))
  s<-list(current=file.path(root,"current"),archive=file.path(root,"archive"),current_files="map.png",archive_files=character(),
    ui_hashes=tools::md5sum(file.path(root,"preview/index.html")))
  get<-function(path,method="GET")connected_explorer_response(list(PATH_INFO=path,REQUEST_METHOD=method),root,s)
  dir.create(file.path(root,"archive/months/2025-01"),recursive=TRUE)
  original<-file.path(root,"archive/months/2025-01/explorer.js")
  writeLines("frozen original",original)
  writeLines("deferred local adapter",file.path(root,"overrides/2025-01-explorer.js"))
  s$archive_files<-"months/2025-01/explorer.js"
  testthat::expect_match(rawToChar(get("/archive/wy2025/months/2025-01/explorer.js")$body),"deferred local adapter")
  testthat::expect_identical(readLines(original),"frozen original")
  before<-tools::md5sum(file.path(root,"current/map.png"))
  testthat::expect_identical(get("/")$status,200L)
  testthat::expect_identical(get("/current/index.html")$status,200L)
  testthat::expect_identical(get("/current/map.png")$body,as.raw(c(1,2,3)))
  testthat::expect_identical(get("/current/map.png","HEAD")$body,raw())
  testthat::expect_identical(get("/")$headers[["X-SWC-Connected-Preview"]],"multi-year-v3")
  testthat::expect_identical(get("/current/secret.txt")$status,404L)
  testthat::expect_identical(get("/current/../secret.txt")$status,400L)
  testthat::expect_identical(get("/current/%2e%2e/secret.txt")$status,400L)
  testthat::expect_identical(get("/current/%5csecret.txt")$status,400L)
  testthat::expect_identical(get("/","POST")$status,405L)
  testthat::expect_identical(before,tools::md5sum(names(before)))
  dir.create(file.path(root,"archive2"))
  writeLines("year 2026",file.path(root,"archive2/map.png"))
  s$archives<-list(wy2025=list(directory=s$archive,files=s$archive_files),wy2026=list(directory=file.path(root,"archive2"),files="map.png"))
  testthat::expect_match(rawToChar(get("/archive/wy2026/map.png")$body),"year 2026")
  testthat::expect_identical(get("/archive/wy2024/map.png")$status,404L)
  testthat::expect_identical(get("/archive/wy2026/months/2025-01/explorer.js")$status,404L)
  writeLines('{"context":"original recent buffer"}',file.path(root,"current/daily-data.json"))
  writeLines('{"selection":"routing dates only"}',file.path(root,"overrides/current-daily-data.json"))
  s$current_files<-c(s$current_files,"daily-data.json")
  testthat::expect_match(rawToChar(get("/current/daily-data.json")$body),"original recent buffer",fixed=TRUE)
})

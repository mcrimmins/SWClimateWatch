testthat::test_that("application asset URLs follow contents and unchanged builds remain stable",{
  dir<-withr::local_tempdir()
  writeLines('<link href="explorer.css?v=old"><script src="explorer.js?v=old" defer></script><p>Snow — rain</p>',file.path(dir,"index.html"),useBytes=TRUE)
  writeLines("body{color:blue}",file.path(dir,"explorer.css"));writeLines("const version=1;",file.path(dir,"explorer.js"))
  files<-swc_cache_version_app(dir)
  testthat::expect_length(files,3)
  before<-tools::md5sum(file.path(dir,c("index.html",files)));mtime<-file.info(file.path(dir,c("index.html",files)))$mtime
  swc_cache_version_app(dir)
  testthat::expect_identical(tools::md5sum(file.path(dir,c("index.html",files))),before)
  testthat::expect_identical(file.info(file.path(dir,c("index.html",files)))$mtime,mtime)
  html<-paste(readLines(file.path(dir,"index.html"),encoding="UTF-8"),collapse="\n")
  testthat::expect_match(html,"explorer\\.swc-[a-f0-9]{16}\\.js")
  testthat::expect_match(html,"Snow — rain",fixed=TRUE)
  testthat::expect_true(endsWith(rawToChar(readBin(file.path(dir,"index.html"),"raw",n=file.info(file.path(dir,"index.html"))$size)),"\n"))
  testthat::expect_false(grepl("?v=old",html,fixed=TRUE))
  writeLines("const version=2;",file.path(dir,"explorer.js"))
  updated<-swc_cache_version_app(dir)
  testthat::expect_equal(length(setdiff(updated,files)),1)
  testthat::expect_silent(swc_cache_validate_app(dir))
  writeLines("damaged",file.path(dir,grep("\\.js$",updated,value=TRUE)))
  testthat::expect_error(swc_cache_validate_app(dir),"stale")
})
testthat::test_that("asset versioning leaves external URLs and data references alone",{
  dir<-withr::local_tempdir();index<-file.path(dir,"index.html")
  html<-'<script src="https://example.com/code.js"></script><iframe src="seasonal/index.html"></iframe><img src="map.png">'
  writeLines(html,index);before<-tools::md5sum(index)
  testthat::expect_length(swc_cache_version_app(dir),0)
  testthat::expect_identical(tools::md5sum(index),before)
})

july_test_root<-normalizePath(testthat::test_path("..",".."),winslash="/",mustWork=TRUE)
source(file.path(july_test_root,"R/daily-explorer-july-pilot.R"))
testthat::test_that("July requires complete preceding weather windows and no future dates",{
  target<-july_pilot_dates();support<-july_pilot_support()
  testthat::expect_length(target,31L);testthat::expect_length(support,60L)
  testthat::expect_identical(target[c(1,31)],c("2025-07-01","2025-07-31"))
  testthat::expect_identical(support[c(1,60)],c("2025-06-02","2025-07-31"))
  for(end in target)for(n in c(1L,7L,30L))testthat::expect_true(all(as.character(seq(as.Date(end)-n+1,as.Date(end),by="day"))%in%support))
})
testthat::test_that("input cache guards reject missing and modified files",{
  withr::local_dir(july_test_root)
  root<-tempfile("july-input-test-",tmpdir="data/diagnostics");dir.create(root)
  date<-"2025-07-01";dir.create(file.path(root,"inputs",date),recursive=TRUE)
  testthat::expect_null(july_pilot_input(root,date))
  field<-file.path(root,"field.grb");index<-file.path(root,"source.idx")
  writeBin(charToRaw("cache fixture"),field);writeLines("index fixture",index)
  make<-function(fields)data.frame(date,field=fields,path=field,index=index,md5=unname(tools::md5sum(field)),index_md5=unname(tools::md5sum(index)),ready=TRUE)
  x<-list(date=date,base=make(c("height500","pwat","u250","v250")),overlay=make(c("mslp","u850","v850")))
  x$digest<-digest::digest(list(x$base,x$overlay),algo="sha256")
  saveRDS(x,file.path(root,"inputs",date,"complete.rds"))
  testthat::expect_identical(july_pilot_input(root,date),x)
  writeLines("changed",index);testthat::expect_null(july_pilot_input(root,date))
})
testthat::test_that("preparation has an explicit offline gate and bounded batches",{
  withr::local_dir(july_test_root)

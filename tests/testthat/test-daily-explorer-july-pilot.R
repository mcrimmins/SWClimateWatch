  testthat::expect_error(build_daily_explorer_july(max_end_dates=32L),"Bound rendering")
  # Missing source data with downloads off must stop before any downloader runs.
  e<-new.env(parent=environment());sys.source(file.path(july_test_root,"R/daily-explorer-july-pilot.R"),envir=e)
  root<-tempfile("july-offline-",tmpdir="data/diagnostics");dir.create(root)
  e$july_pilot_root<-function()root
  e$weather_period_plan<-function(...)data.frame(ready=FALSE)
  e$weather_period_download<-function(...)stop("NETWORK MUST NOT RUN")
  testthat::expect_error(e$prepare_daily_explorer_july(download=FALSE),"Set options")
})

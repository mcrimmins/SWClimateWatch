flow_daily_project<-normalizePath(testthat::test_path("../.."),winslash="/",mustWork=TRUE)
source(file.path(flow_daily_project,"R/streamflow-daily.R"))

testthat::test_that("Streamflow is opt-in and requires connected publication",{
  withr::local_envvar(c(SWC_STREAMFLOW="false"))
  testthat::expect_identical(update_streamflow_daily()$status,"DISABLED")
  withr::local_envvar(c(SWC_STREAMFLOW="true",SWC_DAILY_CONNECTED="false"))
  testthat::expect_error(streamflow_daily_guard(),"requires the connected")
})
testthat::test_that("snapshot seals reject changed files and traversal",{
  d<-tempfile();dir.create(d);withr::defer(unlink(d,recursive=TRUE))
  writeLines("original",file.path(d,"test.json"));streamflow_seal_snapshot(d)
  writeLines("modified",file.path(d,"test.json"))
  testthat::expect_error(streamflow_verify_snapshot(d),"Modified Streamflow snapshot")
  jsonlite::write_json(list(list(path="../escape",sha256="x")),file.path(d,"snapshot-seal.json"),auto_unbox=TRUE)
  testthat::expect_error(streamflow_verify_snapshot(d),"Unsafe snapshot")
})
testthat::test_that("failed refresh retains sealed observations and reports partial status",{
  d<-tempfile();dir.create(d);withr::defer(unlink(d,recursive=TRUE))
  env<-new.env(parent=globalenv());sys.source(file.path(flow_daily_project,"R/streamflow-daily.R"),env)
  env$streamflow_daily_root<-function()d
  env$streamflow_daily_guard<-function()TRUE
  env$streamflow_verify_snapshot<-function(directory)list(cutoff="2026-11-25",gauges=as.list(1:32))
  withr::local_envvar(c(SWC_STREAMFLOW="true"));withr::local_dir(flow_daily_project)
  dir.create(file.path(d,"release"));writeLines("keep",file.path(d,"release/observations"))
  result<-env$update_streamflow_daily(as.Date("2026-11-27"),run=function()stop("source timeout"))
  testthat::expect_identical(result$status,"PARTIAL")
  testthat::expect_identical(result$cutoff,"2026-11-25")
  testthat::expect_identical(readLines(file.path(d,"release/observations")),"keep")
  testthat::expect_match(result$error,"source timeout")
  env$streamflow_verify_snapshot<-function(directory)stop("no verified snapshot")
  result<-env$update_streamflow_daily(as.Date("2026-11-27"),run=function()stop("source timeout"))
  testthat::expect_identical(result$status,"UNAVAILABLE")
})
testthat::test_that("successful retry promotes only the validated requested cutoff",{
  d<-tempfile();dir.create(d);withr::defer(unlink(d,recursive=TRUE))
  env<-new.env(parent=globalenv());sys.source(file.path(flow_daily_project,"R/streamflow-daily.R"),env)
  env$streamflow_daily_root<-function()d;env$streamflow_daily_guard<-function()TRUE
  env$streamflow_snapshot_check<-function(directory)list(cutoff="2026-11-26",gauges=as.list(1:32))
  env$streamflow_verify_snapshot<-function(directory)list(cutoff="2026-11-26",gauges=as.list(1:32))
  withr::local_envvar(c(SWC_STREAMFLOW="true"));withr::local_dir(flow_daily_project)
  dir.create(file.path(d,"release"));writeLines("old",file.path(d,"release/observations"))
  candidate<-file.path(d,"candidate");dir.create(candidate);writeLines("new",file.path(candidate,"observations"))
  run<-function()list(viewer=candidate,summary=list(complete_source_refresh=TRUE,requests=32L))
  result<-env$update_streamflow_daily(as.Date("2026-11-27"),run=run)
  testthat::expect_identical(result$status,"READY")
  testthat::expect_identical(readLines(file.path(d,"release/observations")),"new")
  testthat::expect_identical(readLines(file.path(d,"previous/observations")),"old")
  env$streamflow_snapshot_check<-function(directory)list(cutoff="2026-11-25",gauges=as.list(1:32))
  result<-env$update_streamflow_daily(as.Date("2026-11-27"),run=run)
  testthat::expect_identical(result$status,"PARTIAL")
  testthat::expect_identical(readLines(file.path(d,"release/observations")),"new")
  testthat::expect_match(result$error,"cutoff differs")
})

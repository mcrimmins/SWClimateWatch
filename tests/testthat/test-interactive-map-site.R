testthat::test_that("site packaging versions controls and validates complete rendered assets", {
  root <- tempfile("interactive-site-"); dir.create(root)
  on.exit(unlink(root, recursive = TRUE), add = TRUE)
  pilot <- file.path(root, "pilot"); site <- file.path(root, "site")
  dir.create(pilot); dir.create(file.path(site, "pages"), recursive = TRUE)
  for (name in c("pilot.js", "pilot.css", "leaflet.js", "leaflet.css", "leaflet-package-LICENSE", "boundaries.json"))
    writeLines("fixture", file.path(pilot, name))
  writeLines('<html><head><link href="pilot.css"><link href="leaflet.css"></head><body><a href="https://cales.arizona.edu/climate/watch/pages/monthly-climate.html">Monthly</a><script src="pilot.js"></script><script src="leaflet.js"></script></body></html>', file.path(pilot, "index.html"))
  payload <- file.path(pilot, "test.bin")
  writeBin(as.raw(1:8), payload); writeLines(unname(tools::md5sum(payload)), paste0(payload, ".md5"))
  jsonlite::write_json(list(layers = list(precipitation = list(file = "test.bin", bytes = 8L))),
    file.path(pilot, "manifest.json"), auto_unbox = TRUE)
  frame <- '<iframe src="../interactive-maps/index.html?embedded=1"></iframe>'
  writeLines(frame, file.path(site, "pages/interactive-maps.qmd"))
  testthat::expect_equal(stage_interactive_map_site(pilot, site)$status, "PASS")
  index <- paste(readLines(file.path(site, "interactive-maps/index.html")), collapse = "")
  testthat::expect_match(index, 'pilot-[0-9a-f]{12}\\.js')
  testthat::expect_match(index, '../pages/monthly-climate.html', fixed = TRUE)
  testthat::expect_false(file.exists(file.path(site, "interactive-maps/test.bin.md5")))
  obsolete <- file.path(site,"interactive-maps/current-old_product-1234567890abcdef.bin")
  writeBin(as.raw(1:4),obsolete)
  unrelated <- file.path(site,"interactive-maps/notes.txt");writeLines("retain",unrelated)
  stage_interactive_map_site(pilot,site)
  testthat::expect_false(file.exists(obsolete))
  testthat::expect_true(file.exists(unrelated))
  # Rebuilding after a control change must generate a new browser asset URL.
  writeLines("changed fixture", file.path(pilot, "pilot.js"))
  stage_interactive_map_site(pilot, site)
  testthat::expect_false(identical(index, paste(readLines(file.path(site, "interactive-maps/index.html")), collapse = "")))
  rendered <- file.path(site, "_site"); dir.create(file.path(rendered, "pages"), recursive = TRUE)
  file.copy(file.path(site, "interactive-maps"), rendered, recursive = TRUE)
  html <- paste0('<nav><a href="interactive-maps.html">Interactive Maps</a></nav>', frame)
  writeLines(html, file.path(rendered, "pages/interactive-maps.html"))
  testthat::expect_equal(validate_interactive_map_site(site, rendered = TRUE)$status, "PASS")
  unlink(file.path(rendered, "interactive-maps/test.bin"))
  testthat::expect_error(validate_interactive_map_site(site, rendered = TRUE), "missing or changed")
  # Source corruption must be rejected before the current page is replaced.
  current <- unname(tools::md5sum(file.path(site, "interactive-maps/index.html")))
  writeBin(as.raw(8:1), payload)
  testthat::expect_error(stage_interactive_map_site(pilot, site), "Unverified pilot payload")
  testthat::expect_identical(unname(tools::md5sum(file.path(site, "interactive-maps/index.html"))), current)
})

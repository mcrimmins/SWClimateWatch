testthat::test_that("integration copying preserves bytes and reuses unchanged files", {
  root <- tempfile(); dir.create(root); on.exit(unlink(root, recursive = TRUE), add = TRUE)
  from <- file.path(root, "source"); to <- file.path(root, "preview")
  dir.create(file.path(from, "details"), recursive = TRUE)
  paths <- c("index.html", "details/1.json")
  writeLines("current page", file.path(from, paths[1])); writeLines('{"uid":1}', file.path(from, paths[2]))
  hashes <- tools::md5sum(file.path(from, paths))
  testthat::expect_equal(station_history_copy(paths, from, to), 2L)
  testthat::expect_identical(unname(tools::md5sum(file.path(to, paths))), unname(hashes))
  testthat::expect_equal(station_history_copy(paths, from, to), 0L)
  testthat::expect_identical(tools::md5sum(file.path(from, paths)), hashes)
  writeLines('{"uid":1,"revision":2}', file.path(from, paths[2]))
  testthat::expect_equal(station_history_copy(paths, from, to), 1L)
  testthat::expect_error(station_history_copy("missing.json", from, to), "Missing integration")
  testthat::expect_error(station_history_copy(paths, from, to, NA_character_), "Invalid source")
})

testthat::test_that("layout refresh is guarded and full validation still detects payload corruption", {
  withr::local_dir(project_root)
  folder <- tempfile(tmpdir = "data/diagnostics"); dir.create(folder)
  on.exit(unlink(folder, recursive = TRUE), add = TRUE)
  source_dir <- file.path(folder,"source"); history <- file.path(folder,"history"); output <- file.path(folder,"preview")
  for (p in c(source_dir,history,output)) dir.create(p)
  for (p in c(source_dir,output)) {
    dir.create(file.path(p,"station-details"));writeLines('{"uid":1}',file.path(p,"station-details/1.json"))
    write.csv(data.frame(uid=1,as_of="2000-01-01"),file.path(p,"station-explorer-data.csv"),row.names=FALSE)
    writeLines('<html><script id="explorer-data" type="application/json">{"as_of":"2000-01-01"}</script></html>',file.path(p,"index.html"))
  }
  custom <- file.path(output,"custom-history");dir.create(custom)
  dir.create(file.path(history,"history/1"),recursive=TRUE);dir.create(file.path(custom,"history/1"),recursive=TRUE)
  writeLines('{"schema":1}',file.path(history,"catalog.json"));file.copy(file.path(history,"catalog.json"),custom)
  files <- "history/1/2000.json";writeLines('{"pcpn":1}',file.path(history,files));file.copy(file.path(history,files),file.path(custom,files))
  hashes <- unname(tools::md5sum(file.path(history,files)))
  saveRDS(list(files=files,md5=hashes),file.path(history,"history/1/build.rds"))
  write.csv(data.frame(status="READY"),file.path(history,"update-summary.csv"),row.names=FALSE)
  write.csv(data.frame(status="READY",current_cutoff="2000-01-01",stations=1,historical_chunks=1),file.path(output,"integration-summary.csv"),row.names=FALSE)
  write.csv(data.frame(file=c("catalog.json",files),md5=unname(tools::md5sum(file.path(history,c("catalog.json",files))))),file.path(output,"history-checksums.csv"),row.names=FALSE)
  result <- build_station_history_integration(source_dir,history,output)
  testthat::expect_equal(result$mode,"assets-only");testthat::expect_equal(result$history_files_hashed,0L)
  testthat::expect_equal(validate_station_history_integration(output)$scope,"full-payloads")
  writeLines('{"pcpn":999}',file.path(custom,files))
  testthat::expect_error(validate_station_history_integration(output),"checksum mismatch")
  writeLines('{"uid":1,"new":true}',file.path(source_dir,"station-details/1.json"))
  testthat::expect_error(build_station_history_integration(source_dir,history,output),"Source data differ")
})

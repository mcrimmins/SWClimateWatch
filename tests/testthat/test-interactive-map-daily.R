testthat::test_that("daily export retains native double differences, missing pairs and revision reuse", {
  folder <- tempfile("daily-map-"); dir.create(folder)
  on.exit(unlink(folder, recursive = TRUE), add = TRUE)
  r <- terra::rast(nrows = 2, ncols = 2, xmin = -111, xmax = -110, ymin = 33, ymax = 34, crs = "EPSG:4326")
  values <- list(observed = c(80 + 1/32768, NA, 90.5, 60.125), normal = c(78.25, 80, NA, 59.0625))
  hashes <- c(observed = "fixture-observed", normal = "fixture-normal")
  build <- function() interactive_daily_export("daily-tmean-2026-10-31", "2026-10-31", "tmean", values, r, hashes, TRUE, folder)
  first <- build()
  testthat::expect_true(all(first$checks$passed))
  testthat::expect_false(first$summary$reused)
  testthat::expect_equal(first$entry$fields$observed$type, "float64")
  testthat::expect_true(first$entry$derived_departure)
  path <- file.path(folder, first$entry$file)
  con <- file(path, "rb"); observed <- readBin(con, "numeric", n = 4, size = 8, endian = "little")
  normal <- readBin(con, "numeric", n = 4, size = 8, endian = "little"); close(con)
  testthat::expect_identical(observed, values$observed)
  testthat::expect_identical(normal, values$normal)
  testthat::expect_identical(is.na(observed-normal), c(FALSE,TRUE,TRUE,FALSE))
  testthat::expect_true(build()$summary$reused)
  writeBin(rep(as.raw(0), first$entry$bytes), path)
  testthat::expect_false(build()$summary$reused)
  hashes[["normal"]] <- "revised-normal"
  testthat::expect_false(identical(build()$entry$file, first$entry$file))
})

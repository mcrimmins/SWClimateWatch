source(file.path(project_root,"R","daily-explorer-site.R"))
source(file.path(project_root,"R","daily-explorer-weather-means-preview.R"))
testthat::test_that("local integration verifies period outputs and stays outside site",{
  withr::local_dir(project_root)
  root<-withr::local_tempdir(tmpdir=file.path(project_root,"data","diagnostics"))
  src<-file.path(root,"source");means<-file.path(root,"means");out<-file.path(root,"preview")
  dir.create(file.path(src,"maps"),recursive=TRUE);dir.create(means)
  end<-"2026-10-05";image<-paste0("maps/",end,"-pcpn-observed.png")
  writeLines("map",file.path(src,image))
  jsonlite::write_json(list(schema_version=1L,latest_cached_date=end,days=list(list(date=end,water_year=2027,images=list(pcpn_observed=image)))),
    file.path(src,"daily-data.json"),auto_unbox=TRUE)
  for(days in c(1L,7L,30L)) {
    d<-file.path(means,paste0(days,"day"));dir.create(d)
    paths<-file.path(d,c(paste0(c("height500-","pwat-","jet250-"),days,"day.png"),"mean-native-grid.rds"))
    for(p in paths)writeLines("fixture",p)
    saveRDS(list(md5=unname(tools::md5sum(paths))),file.path(d,"complete.rds"))
    p<-file.path(d,paste0("pwat-overlay-",days,"day.png"));writeLines("overlay",p)
    saveRDS(list(md5=unname(tools::md5sum(p))),paste0(p,".rds"))
  }
  write.csv(data.frame(days=c(1,7,30),start=as.character(as.Date(end)-c(0,6,29)),end=end),file.path(means,"period-summary.csv"),row.names=FALSE)
  testthat::expect_error(stage_daily_explorer_weather_means_preview(src,means,output_dir="site/forbidden-preview"),"separate preview")
  result<-stage_daily_explorer_weather_means_preview(src,means,output_dir=out)
  testthat::expect_equal(result$requests,0)
  testthat::expect_equal(result$mean_maps,6)
  payload<-jsonlite::read_json(file.path(out,"daily-data.json"))
  testthat::expect_false(payload$publication_mode)
  testthat::expect_true(payload$circulation_period_means_preview)
  manifest<-jsonlite::read_json(file.path(out,"circulation-means-manifest.json"))
  testthat::expect_length(manifest$periods,2)
  testthat::expect_true(all(file.exists(file.path(out,unlist(lapply(manifest$periods,`[[`,"images"))))))
  writeLines("damaged",file.path(means,"30day","jet250-30day.png"))
  testthat::expect_error(stage_daily_explorer_weather_means_preview(src,means,output_dir=out),"checksum mismatch")
})

for(module in c("config.R","prism-freeze-free-season.R","rebuild-cached-raster-maps.R"))
  source(file.path(project_root,"R",module))

testthat::test_that("cached rebuild validates both exact-date inputs before installing any map", {
  root <- tempfile("cached-raster-rebuild-");dir.create(root)
  on.exit(unlink(root,recursive=TRUE),add=TRUE)
  maps <- file.path(root,"maps");dir.create(maps)
  ids <- paste0("mint_freeze_free_",c("length","departure"))
  images <- paste0(c("length","departure"),".png")
  for(image in images)writeLines("unchanged map fixture",file.path(maps,image))
  products <- setNames(lapply(images,function(image)list(image=image)),ids)
  config <- file.path(root,"config.yml");yaml::write_yaml(list(defaults=list(enabled=TRUE),products=products),config)
  status <- file.path(root,"status.csv")
  hashes <- unname(tools::md5sum(file.path(maps,images)))
  write.csv(data.frame(id=ids,enabled=TRUE,validation_status="PASS",actual_data_date="2026-11-03",image_md5=hashes),status,row.names=FALSE)
  r <- terra::rast(nrows=2,ncols=2,xmin=-112,xmax=-111,ymin=33,ymax=34,crs="EPSG:4326")
  terra::values(r)<-1:4;terra::time(r)<-as.Date("2026-11-03")
  source <- prism_freeze_free_output_path("length",2026,as.Date("2026-11-03"),processed_dir=file.path(root,"processed"))
  dir.create(dirname(source),recursive=TRUE);terra::writeRaster(r,source)
  args <- list(output_dir=file.path(root,"out"),processed_dir=file.path(root,"processed"),source_maps_dir=maps,
    status_path=status,config_path=config,report_dir=file.path(root,"report"))
  testthat::expect_error(do.call(rebuild_cached_freeze_free_maps,args),"Exact cached derived grid missing")
  testthat::expect_false(dir.exists(args$output_dir))
  second <- prism_freeze_free_output_path("departure",2026,as.Date("2026-11-03"),processed_dir=args$processed_dir)
  dir.create(dirname(second),recursive=TRUE);terra::time(r)<-as.Date("2026-11-02");terra::writeRaster(r,second)
  testthat::expect_error(do.call(rebuild_cached_freeze_free_maps,args),"date mismatch")
  testthat::expect_false(dir.exists(args$output_dir))
  testthat::expect_identical(unname(tools::md5sum(file.path(maps,images))),hashes)
})

report_retry_root<-normalizePath(testthat::test_path("..",".."),winslash="/",mustWork=TRUE)
source(file.path(report_retry_root,"R/storm-reports-pilot.R"))
testthat::test_that("archive timeout and failure retries are bounded without changing defaults",{
  withr::local_options(list(swc.storm_reports.timeout=NULL,swc.storm_reports.max_tries=NULL))
  original<-storm_reports_archive_request("2026-01-01","2026-02-01")
  testthat::expect_identical(original$options$timeout_ms,45000)
  testthat::expect_identical(original$policies$retry_max_tries,1L)
  larger<-storm_reports_archive_request("2026-01-01","2026-02-01",120,3L)
  testthat::expect_identical(larger$options$timeout_ms,120000)
  testthat::expect_identical(larger$policies$retry_max_tries,3L)
  testthat::expect_true(larger$policies$retry_on_failure)
  testthat::expect_error(storm_reports_archive_request("a","b",181,3),"Bound report")
  testthat::expect_error(storm_reports_archive_request("a","b",120,4),"Bound report")
})
testthat::test_that("failed transfers retain good caches and never create empty coverage",{
  e<-new.env(parent=globalenv());sys.source(file.path(report_retry_root,"R/storm-reports-pilot.R"),envir=e)
  root<-tempfile();dir.create(root);withr::defer(unlink(root,recursive=TRUE))
  path<-file.path(root,"2026-01-01_2026-02-01.rds")
  cached<-list(start="2026-01-01",end="2026-02-01",fetched_utc="test",url="https://example.com",raw=list())
  saveRDS(cached,path);before<-tools::md5sum(path)
  e$normalize_storm_reports<-function(...)list()
  testthat::local_mocked_bindings(req_perform=function(...)stop("simulated timeout"),.package="httr2")
  testthat::expect_identical(e$read_storm_reports_cache("2026-01-01","2026-02-01",cache_dir=root),cached)
  testthat::expect_error(e$read_storm_reports_cache("2026-01-01","2026-02-01",refresh=TRUE,cache_dir=root),"simulated timeout")
  testthat::expect_identical(before,tools::md5sum(path))
  testthat::expect_error(e$read_storm_reports_cache("2026-02-01","2026-03-01",cache_dir=root),"simulated timeout")
  testthat::expect_false(file.exists(file.path(root,"2026-02-01_2026-03-01.rds")))
})

const assert=require('node:assert/strict');
const {select,windowFor}=require('../scripts/nws-hazards-assets/hazard-model.js');
const event=(id,start,end,states=['AZ'])=>({id,title:'Flood Warning',wfo:'PSR',significance:'W',segments:[{start,end,states,zone:'AZC013'}]});
const rows=[event('carry','2024-06-30T00:00:00Z','2024-07-01T12:00:00Z'),event('new','2024-07-01T12:00:00Z','2024-07-02T00:00:00Z',['NM']),event('expired','2024-06-30T00:00:00Z','2024-07-01T00:00:00Z')];
const w=windowFor('2024-07-01',1,'utc','2024-07-01');
assert.deepEqual(select(rows,w).map(e=>e.id),['carry','new']);
assert.deepEqual(select(rows,w,{region:'AZ'}).map(e=>e.id),['carry']);
assert.deepEqual(select(rows,w,{mode:'starts'}).map(e=>e.id),['new']);
assert.equal(select(rows,w,{kind:'Y'}).length,0);
assert.equal(select(rows,w,{type:'Other'}).length,0);
assert.equal(select(rows,w,{search:'not present'}).length,0);
const prism=windowFor('2024-07-02',1,'prism','2024-07-01');
assert.deepEqual(select(rows,prism).map(e=>e.id),['new']);
assert.equal(windowFor('2024-03-01',7,'utc','2024-02-01').end-windowFor('2024-03-01',7,'utc','2024-02-01').start,7*86400000);
assert.equal(windowFor('2024-01-01',30,'prism','2024-01-01').truncated,true);
const zones=event('zones','2024-07-01T00:00:00Z','2024-07-02T00:00:00Z');zones.segments.push({...zones.segments[0],zone:'AZC001'});
assert.equal(select([zones],w).length,1);assert.equal(select([zones],w)[0].segments.length,2);
assert.equal(select([],w).length,0);
console.log('PASS: carry-in, half-open noon/UTC intervals, region/type/level/search, effective starts, leap dates, truncation and event deduplication.');
const {structuredDetails}=require('../scripts/nws-hazards-assets/hazard-model.js');
assert.deepEqual(structuredDetails([{tags:{wind_mph:0,hail_inches:null,flood_severity:'0',flood_record:'OO',gauge_id:'00000',emergency_lifecycle:false}}]),[]);
const details=Object.fromEntries(structuredDetails([{tags:{wind_mph:60,hail_inches:1.25,tornado:'RADAR INDICATED',flood_cause:'ER',emergency_lifecycle:true}},{tags:{wind_mph:70,flood_cause:'ER'}}]));
assert.equal(details['Wind gust tag'],'60 mph, 70 mph');assert.equal(details['Hail size tag'],'1.25 in.');
assert.equal(details['Tornado tag'],'Radar Indicated');assert.equal(details['Flood cause'],'Excessive rainfall');
assert.match(details['Archive emergency flag'],/during this event/);
assert.equal(Object.fromEntries(structuredDetails([{tags:{flood_severity:'U'}}]))['Flood severity'],'Unknown');
assert.match(Object.fromEntries(structuredDetails([{tags:{flood_cause:'ZZ'}}]))['Flood cause'],/Code ZZ/);
console.log('PASS: structured tag units, sentinel guards, repeated/varied updates and lifecycle emergency wording.');

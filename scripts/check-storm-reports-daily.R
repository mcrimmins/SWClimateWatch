source("R/storm-reports-daily.R")
if(!storm_reports_enabled())stop("Set SWC_STORM_REPORTS=true for this check.")
validate_storm_reports_daily()
x<-read.csv("data/diagnostics/storm-reports-daily/workflow-status.csv")
payload<-jsonlite::read_json("site/daily-explorer/daily-data.json")
cutoff<-max(vapply(payload$days,`[[`,character(1),"date"))
if(nrow(x)!=1L||!identical(x$cutoff,cutoff))stop("Daily report refresh does not match the current Explorer date.")
print(x,row.names=FALSE)
cat("PASS: daily report refresh matches source and rendered Explorer through",cutoff,"\n")
